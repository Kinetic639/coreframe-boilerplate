"use client";

import { planningRead } from "@/lib/planning/read";
import { useState } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { useTranslations } from "next-intl";
import { Link2Off, Loader2, Plus, Printer, QrCode } from "lucide-react";
import { toast } from "react-toastify";
import { Button } from "@/components/ui/button";
import { QrAssignDialog, QrPrintLabelDialog } from "@/components/features/qr";
import {
  assignQrToPlanningTaskAction,
  createAndAssignQrToPlanningTaskAction,
} from "@/app/actions/planning";
import { revokeQrAction } from "@/app/actions/qr/revoke";
import { usePermissions } from "@/hooks/v2/use-permissions";
import { QR_CREATE, QR_EXPORT } from "@/lib/constants/permissions";

/**
 * The task's QR code: show it, print its label, give the task a new one (or
 * a scanned stuck-on label), or unlink it. No picking from a pool of codes
 * generated by hand beforehand.
 */
export function TaskQrSection({
  taskId,
  taskTitle,
  canUpdate,
}: {
  taskId: string;
  taskTitle?: string;
  canUpdate: boolean;
}) {
  const t = useTranslations("modules.planning");
  const tQr = useTranslations("modules.qr.assign");
  const { can } = usePermissions();
  const queryClient = useQueryClient();
  const queryKey = ["planning-task-editor", "qr", taskId];
  const assignment = useQuery({
    queryKey,
    queryFn: async () => {
      const result = await planningRead("taskQrAssignment", taskId);
      if ("error" in result) throw new Error(result.error);
      return result.data;
    },
    staleTime: 60 * 1000,
  });
  const [assignOpen, setAssignOpen] = useState(false);
  const [printOpen, setPrintOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const name = taskTitle?.trim() || t("tasks.unlabelled");

  const assigned = () => {
    toast.success(t("tasks.qrCodeAssigned"));
    void queryClient.invalidateQueries({ queryKey });
    return null;
  };

  const unlink = async () => {
    if (!assignment.data) return;
    setBusy(true);
    const result = await revokeQrAction({ qrCodeId: assignment.data.qrCodeId });
    setBusy(false);
    if (!result.success) {
      toast.error(t("tasks.qrCodeUnlinkFailed"));
      return;
    }
    toast.success(t("tasks.qrCodeUnlinked"));
    queryClient.setQueryData(queryKey, null);
  };

  return (
    <section className="space-y-2">
      <h3 className="flex items-center gap-1.5 text-xs font-medium uppercase tracking-wide text-muted-foreground">
        <QrCode className="h-3.5 w-3.5" />
        {t("tasks.qrCode")}
      </h3>
      {assignment.isPending ? (
        <Loader2 className="h-4 w-4 animate-spin text-muted-foreground" />
      ) : assignment.data ? (
        <div className="space-y-2">
          <div className="rounded-md bg-muted/50 px-2.5 py-1.5 text-xs">
            <p className="truncate font-medium">{assignment.data.label ?? t("tasks.unlabelled")}</p>
            <p className="truncate font-mono text-muted-foreground">{assignment.data.token}</p>
          </div>
          {can(QR_EXPORT) ? (
            <Button
              variant="outline"
              size="sm"
              className="h-7 w-full text-xs"
              onClick={() => setPrintOpen(true)}
            >
              <Printer className="mr-1.5 h-3 w-3" />
              {tQr("print")}
            </Button>
          ) : null}
          {canUpdate ? (
            <Button
              variant="outline"
              size="sm"
              className="h-7 w-full text-xs text-destructive hover:text-destructive"
              onClick={() => void unlink()}
              disabled={busy}
            >
              <Link2Off className="mr-1.5 h-3 w-3" />
              {t("tasks.unlink")}
            </Button>
          ) : null}
          <QrPrintLabelDialog
            open={printOpen}
            onOpenChange={setPrintOpen}
            qrCodeId={assignment.data.qrCodeId}
            name={assignment.data.label ?? name}
          />
        </div>
      ) : canUpdate ? (
        <>
          <Button
            variant="outline"
            size="sm"
            className="h-7 w-full text-xs"
            onClick={() => setAssignOpen(true)}
          >
            <Plus className="mr-1.5 h-3 w-3" />
            {t("tasks.assignQrCode")}
          </Button>
          <QrAssignDialog
            open={assignOpen}
            onOpenChange={setAssignOpen}
            objectName={name}
            canCreate={can(QR_CREATE)}
            onCreate={async () => {
              const result = await createAndAssignQrToPlanningTaskAction({
                taskId,
                label: taskTitle ?? null,
              });
              return result.success ? assigned() : t("tasks.qrCodeAssignFailed");
            }}
            onScanned={async (lookup) => {
              const result = await assignQrToPlanningTaskAction({ qrCodeId: lookup.id, taskId });
              return result.success ? assigned() : t("tasks.qrCodeAssignFailed");
            }}
          />
        </>
      ) : (
        <p className="text-xs text-muted-foreground">{t("tasks.noQrCodeAssigned")}</p>
      )}
    </section>
  );
}
